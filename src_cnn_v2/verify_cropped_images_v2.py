# src_cnn_v2/verify_cropped_images_v2.py
"""
A utility script to visually verify the output of the NEW data creation pipeline.

This script verifies the final .npy crops by:
1. Reading a sample from the final metadata (e.g., val_metadata.csv).
2. Finding the original raw .mat video.
3. Finding the corresponding _coordinates.json file generated by find_leaking_holes.py.
4. Extracting the precise (y, x) coordinates used for cropping.
5. Re-creating the crop box on the original video frame to confirm it is centered correctly.
"""
import os
import sys
import pandas as pd
import numpy as np
import scipy.io
import matplotlib.pyplot as plt
import matplotlib.patches as patches
import random
import glob
import argparse
import json

# --- Add project root to sys.path ---
project_root = os.path.abspath(os.path.join(os.path.dirname(__file__), '..'))
sys.path.insert(0, project_root)

from src_cnn_v2 import config_v2 as cfg

def main():
    parser = argparse.ArgumentParser(description="Visually verify the cropped dataset from the new coordinate-based pipeline.")
    parser.add_argument("--num_samples", type=int, default=10, help="Number of random samples to visualize.")
    parser.add_argument("--split", type=str, default="val", choices=["train", "val", "test"],
                        help="Which split's metadata to use for verification.")
    parser.add_argument("--raw_video_dir", type=str, required=True,
                        help="Path to the parent directory containing raw .mat video datasets.")
    parser.add_argument("--coord_dir", type=str, required=True,
                        help="Path to the parent directory containing the generated coordinate files (e.g., 'Output_SAM/datasets').")
    args = parser.parse_args()

    print(f"--- Verifying V2 Cropped Dataset for Experiment: {cfg.EXPERIMENT_NAME} ---")
    print(f"  - Using data split from random seed: {cfg.RANDOM_STATE}")
    print(f"  - Will visualize {args.num_samples} random samples from the '{args.split}' split.")

    DATASET_DIR = cfg.DATASET_DIR
    
    if args.split == 'train':
        METADATA_PATH = cfg.TRAIN_METADATA_PATH
    elif args.split == 'val':
        METADATA_PATH = cfg.VAL_METADATA_PATH
    else: # test
        METADATA_PATH = cfg.TEST_METADATA_PATH
    
    VERIFICATION_DIR = os.path.join(cfg.OUTPUT_DIR, "crop_verification_v2")
    os.makedirs(VERIFICATION_DIR, exist_ok=True)
    print(f"Saving output plots to: {VERIFICATION_DIR}")

    try:
        df_meta = pd.read_csv(METADATA_PATH)
    except FileNotFoundError:
        sys.exit(f"FATAL: Metadata file not found at '{METADATA_PATH}'. Please run the full pipeline first.")

    # We only care about the original, un-augmented samples for verification
    df_meta_orig = df_meta[~df_meta['sample_id'].str.contains('_aug_')].copy()
    num_to_sample = min(args.num_samples, len(df_meta_orig))
    if num_to_sample == 0:
        print("No original samples found to verify."); return
        
    random_samples = df_meta_orig.sample(n=num_to_sample, random_state=cfg.RANDOM_STATE)

    for index, row in random_samples.iterrows():
        try:
            sample_id = row['sample_id']
            video_id = row['video_id']
            hole_id_full = str(row['hole_id'])
            numeric_hole_id = hole_id_full.split('_')[0]
            
            print(f"\nProcessing sample: {sample_id} (Video: {video_id}, Hole: {numeric_hole_id})...")

            # --- 1. Find the original raw .mat video file ---
            mat_filepath, found_config_key = (None, None)
            for d_key, d_conf in cfg.DATASET_CONFIGS.items():
                video_search_pattern = os.path.join(args.raw_video_dir, d_conf["dataset_subfolder"], '**', f"{video_id}.mat")
                video_results = glob.glob(video_search_pattern, recursive=True)
                if video_results:
                    mat_filepath, found_config_key = video_results[0], d_key
                    break
            if not mat_filepath: raise FileNotFoundError(f".mat file not found for video_id '{video_id}'")
            
            # --- 2. Find the corresponding coordinates.json file ---
            coord_subfolder = cfg.DATASET_CONFIGS[found_config_key]["dataset_subfolder"]
            coord_search_pattern = os.path.join(args.coord_dir, coord_subfolder, '**', video_id)
            coord_dir_results = glob.glob(coord_search_pattern, recursive=True)
            coord_dir_path = next((path for path in coord_dir_results if os.path.isdir(path)), None)
            if not coord_dir_path: raise FileNotFoundError(f"Coordinate directory not found for video_id '{video_id}'")

            coord_path = os.path.join(coord_dir_path, f"{video_id}_coordinates.json")
            if not os.path.exists(coord_path): raise FileNotFoundError(f"Coordinates file not found: {coord_path}")

            # --- 3. Load the coordinates and find the center for this specific hole ---
            with open(coord_path, 'r') as f:
                all_leaks_in_video = json.load(f)
            
            target_leak_data = next((leak for leak in all_leaks_in_video if str(leak['hole_id']) == numeric_hole_id), None)
            if target_leak_data is None: raise ValueError(f"Numeric Hole ID '{numeric_hole_id}' not found in coordinates file.")

            center_x = target_leak_data['center_x']
            center_y = target_leak_data['center_y']
            
            # --- 4. Load all necessary data for plotting ---
            full_frames = scipy.io.loadmat(mat_filepath).get('TempFrames').astype(np.float32)
            
            cropped_sequence_path = os.path.join(DATASET_DIR, row['image_path'])
            cropped_sequence = np.load(cropped_sequence_path)
            
            # --- 5. Create and save the verification plot ---
            mid_frame_idx = full_frames.shape[2] // 2
            full_frame_mid = full_frames[:, :, mid_frame_idx]
            
            cropped_mid_idx = cropped_sequence.shape[0] // 2
            cropped_frame_mid = cropped_sequence[cropped_mid_idx, :, :]
            
            crop_size = cfg.V2_DATASET_PARAMS["CROP_SIZE"]
            
            fig, (ax1, ax2) = plt.subplots(1, 2, figsize=(12, 6))
            
            ax1.imshow(full_frame_mid, cmap='inferno')
            ax1.set_title(f'Original Frame (Center: {center_x}, {center_y})')
            rect = patches.Rectangle(
                (center_x - crop_size // 2, center_y - crop_size // 2), 
                crop_size, crop_size, 
                linewidth=2, edgecolor='lime', facecolor='none'
            )
            ax1.add_patch(rect)
            ax1.scatter([center_x], [center_y], s=50, c='cyan', marker='+')
            ax1.axis('off')
            
            ax2.imshow(cropped_frame_mid, cmap='inferno')
            ax2.set_title(f'Saved Crop ({crop_size}x{crop_size})')
            ax2.axis('off')
            
            fig.suptitle(f"Verification for: {sample_id}", fontsize=16)
            plt.tight_layout(rect=[0, 0, 1, 0.96])
            
            save_path = os.path.join(VERIFICATION_DIR, f"{sample_id.replace('/', '_')}.png")
            plt.savefig(save_path)
            plt.close(fig)
            print(f"  -> Saved verification plot to {os.path.basename(save_path)}")

        except Exception as e:
            print(f"  -> FAILED to process sample {row.get('sample_id', 'N/A')}. Reason: {type(e).__name__}: {e}")
            continue
            
    print("\n--- Verification Complete ---")

if __name__ == "__main__":
    main()

