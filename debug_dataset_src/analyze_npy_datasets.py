# src_cnn_v2/analyze_npy_datasets.py
"""
A diagnostic script to perform a deep-dive analysis and comparison of
.npy sequence files from different data preparation pipelines.

This script computes statistical summaries and generates plots to visualize the
temporal and spatial characteristics of the data being fed to the models.

How to Run:
  python src_cnn_v2/analysis/analyze_npy_datasets.py \
    --my_npy /path/to/your/pipeline/output.npy \
    --colleague_npy /path/to/your/colleagues/pipeline/output.npy \
    --output_dir analysis_reports/
"""
import os
import sys
import argparse
import numpy as np
import matplotlib.pyplot as plt
import seaborn as sns

# --- Plotting Configuration ---
sns.set_theme(style="whitegrid")

def analyze_npy_file(npy_path, output_dir, prefix='analysis'):
    """
    Loads a single .npy file and performs a detailed statistical and visual analysis.
    """
    print(f"\n--- Analyzing File: {os.path.basename(npy_path)} ---")

    try:
        # Colleague's data is (H, W, T), our pipeline is (T, H, W).
        # We will load and immediately convert to a standard (T, H, W) format.
        data = np.load(npy_path)
        if data.shape[0] < data.shape[2]:
            # This is likely (H, W, T), so transpose it
            data = data.transpose(2, 0, 1)
        
        T, H, W = data.shape
        print(f"  - Shape (T, H, W): ({T}, {H}, {W})")

    except Exception as e:
        print(f"  - ERROR: Could not load or process file. Reason: {e}")
        return

    # --- 1. Statistical Summary ---
    print("\n  [Statistical Summary]")
    print(f"  - Min Value:   {np.min(data):.4f}")
    print(f"  - Max Value:   {np.max(data):.4f}")
    print(f"  - Mean Value:  {np.mean(data):.4f}")
    print(f"  - Std Dev:     {np.std(data):.4f}")
    print(f"  - Median Value:{np.median(data):.4f}")

    # --- 2. Temporal Analysis ---
    # Calculate the mean temperature of the entire crop at each frame
    temporal_profile = np.mean(data, axis=(1, 2))
    time_axis = np.arange(T)

    # --- 3. Spatial Analysis ---
    # Calculate the time-averaged image of the crop
    spatial_profile = np.mean(data, axis=0)

    # --- 4. Generate Combined Plot ---
    fig, axes = plt.subplots(1, 2, figsize=(16, 6))
    fig.suptitle(f"Analysis for: {os.path.basename(npy_path)}", fontsize=16)

    # Plot 1: Temporal Profile (How the crop heats up over time)
    axes[0].plot(time_axis, temporal_profile, lw=2)
    axes[0].set_title("Temporal Profile (Average Crop Value Over Time)")
    axes[0].set_xlabel("Frame Number")
    axes[0].set_ylabel("Mean Pixel Value")

    # Plot 2: Spatial Profile (Where the heat is concentrated)
    sns.heatmap(spatial_profile, cmap='inferno', ax=axes[1])
    axes[1].set_title("Spatial Profile (Time-Averaged Crop)")
    axes[1].set_xlabel("X-pixel")
    axes[1].set_ylabel("Y-pixel")
    axes[1].set_aspect('equal', adjustable='box')


    plot_save_path = os.path.join(output_dir, f"{prefix}_summary.png")
    plt.tight_layout(rect=[0, 0.03, 1, 0.95])
    plt.savefig(plot_save_path)
    plt.close(fig)
    print(f"\n  - Saved analysis plot to: {plot_save_path}")

def main():
    parser = argparse.ArgumentParser(description="Deep analysis tool for .npy sequence files.")
    parser.add_argument("--my_npy", required=True, help="Path to a .npy file generated by YOUR pipeline.")
    parser.add_argument("--colleague_npy", required=True, help="Path to the corresponding .npy file from your colleague's pipeline.")
    parser.add_argument("--output_dir", required=True, help="Directory to save the comparison plots.")
    args = parser.parse_args()

    os.makedirs(args.output_dir, exist_ok=True)

    # Analyze your file
    analyze_npy_file(args.my_npy, args.output_dir, prefix="my_pipeline")

    # Analyze your colleague's file
    analyze_npy_file(args.colleague_npy, args.output_dir, prefix="colleague_pipeline")

    print("\n--- Analysis Complete ---")

if __name__ == "__main__":
    main()

